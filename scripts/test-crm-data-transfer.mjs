#!/usr/bin/env node

import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = process.cwd()
const read = (relativePath) => readFileSync(resolve(root, relativePath), 'utf8')

const migration = read('db/migrations/0129_crm_data_transfers.sql')
const csv = read('app_src/lib/crm/dataTransferCsv.ts')
const persistence = read('app_src/lib/persistence/crmDataTransfers.ts')
const route = read('app_src/app/api/crm/data-transfer/route.ts')
const dialog = read('app_src/components/crm/CrmDataTransferDialog.tsx')
const crmUi = read('app_src/components/crm/CrmSection.tsx')
const contract = read('docs/modules/crm-and-reporting.md')

assert.match(migration, /CREATE TABLE IF NOT EXISTS crm_data_transfer_runs/)
assert.match(migration, /CREATE TABLE IF NOT EXISTS crm_data_transfer_rows/)
assert.match(migration, /FOREIGN KEY \(pipeline_id, run_id\)/)
assert.match(migration, /expires_at timestamptz/)
assert.match(migration, /idempotency_key text/)
assert.match(migration, /observed_source_hash text/)
assert.match(migration, /field_diffs jsonb/)
assert.match(migration, /classification IN \([\s\S]*'create'[\s\S]*'update'[\s\S]*'unchanged'[\s\S]*'ambiguous'[\s\S]*'invalid'/)

assert.match(csv, /CRM_DATA_TRANSFER_MAX_BYTES = 1_048_576/)
assert.match(csv, /CRM_DATA_TRANSFER_MAX_ROWS = 500/)
assert.match(csv, /buildCrmDataTransferCsvSegments/)
assert.match(csv, /crmProductUniquenessConflicts/)
assert.match(csv, /SPREADSHEET_FORMULA_PATTERN/)
assert.match(csv, /CRM_CSV_HEADERS_INVALID/)
assert.match(csv, /CRM_CSV_RECORD_VERSION_REQUIRED/)
assert.match(csv, /crmDataTransferFieldDiffs/)
assert.match(csv, /crmDataTransferNaturalKey/)
assert.doesNotMatch(csv, /delete|archive/i)

assert.match(persistence, /stageCrmRecordWithClient/)
assert.match(persistence, /acquireTransactionAdvisoryLock/)
assert.match(persistence, /FOR UPDATE/)
assert.match(persistence, /observed_updated_at/)
assert.match(persistence, /observed_source_hash/)
assert.match(persistence, /changed after preview; re-run preview/)
assert.match(persistence, /classification === 'create'/)
assert.match(persistence, /classification === 'update'/)
assert.match(persistence, /CRM_CSV_PRODUCT_NAME_CONFLICT/)
assert.match(persistence, /CRM_CSV_PRODUCT_SKU_CONFLICT/)
assert.match(persistence, /exportCrmDataTransferCsvSegments/)
assert.match(persistence, /status = 'applied'/)
assert.match(persistence, /crm\.data_transfer\.previewed/)
assert.match(persistence, /crm\.data_transfer\.applied/)
assert.doesNotMatch(persistence, /enqueueCrmIntegrationAction/)

assert.match(route, /requireResourceEditor\(pipeline\)/)
assert.match(route, /isCrmWritableTransferEntity/)
assert.match(route, /Meetings, interactions, and campaigns are export-only/)
assert.match(route, /Idempotency-Key/)
assert.match(route, /content-length/)
assert.match(route, /file\.size > CRM_DATA_TRANSFER_MAX_BYTES/)
assert.match(route, /X-ClawPilot-Export-Parts/)
assert.match(route, /template.*buildCrmDataTransferCsv/s)
assert.match(route, /Cache-Control': 'private, no-store'/)
assert.doesNotMatch(route, /body\?\.pipelineId|form\.get\('pipelineId'\)/)

assert.match(dialog, /Preview changes/)
assert.match(dialog, /Download template/)
assert.match(dialog, /Existing records are not selected automatically/)
assert.match(dialog, /I reviewed \$\{selectedUpdateCount\}/)
assert.match(dialog, /Download error report/)
assert.match(dialog, /selected\.size > CRM_CSV_MAX_BYTES/)
assert.match(dialog, /row\.diffs\.map/)
assert.match(crmUi, /Export \$\{ENTITY_LABELS\[entity\]\} CSV/)
assert.match(crmUi, /Import \$\{ENTITY_LABELS\[entity\]\} CSV/)
assert.match(crmUi, /downloadCrmCsvExport/)
assert.match(crmUi, /canManageProductIdentities/)
assert.match(crmUi, /CrmDataTransferDialog/)

assert.match(contract, /## CSV Data Transfer/)
assert.match(contract, /two-phase import/)
assert.match(contract, /Meetings, Interactions, and Campaigns are export-only/)
assert.match(contract, /Global ID is the only update identity/)
assert.match(contract, /rechecks `updated_at` plus `source_hash`/)

console.log('CRM CSV data-transfer contracts passed')
