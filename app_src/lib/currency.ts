const supportedCurrencyCodes = new Set<string>(
  SUPPORTED_ISO_4217_CURRENCY_CODES,
)

export function isIso4217CurrencyCode(value: unknown): value is string {
  if (typeof value !== 'string') return false
  const normalized = value.trim().toUpperCase()
  return /^[A-Z]{3}$/.test(normalized) && supportedCurrencyCodes.has(normalized)
}

export function normalizeCurrencyCode(
  value: unknown,
  fallback = DEFAULT_WORKSPACE_CURRENCY_CODE,
): string {
  const normalized = String(value ?? '').trim().toUpperCase()
  return isIso4217CurrencyCode(normalized) ? normalized : fallback
}

export function currencyDisplayName(
  currencyCode: string,
  locale = 'en-US',
): string {
  const normalized = normalizeCurrencyCode(currencyCode)
  try {
    const displayNames = new Intl.DisplayNames([locale], { type: 'currency' })
    return displayNames.of(normalized) || normalized
  } catch {
    return normalized
  }
}
